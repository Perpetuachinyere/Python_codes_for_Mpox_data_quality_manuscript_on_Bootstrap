    R['repcv']={k:(float(np.mean(v)),float(np.std(v,ddof=1)),float(min(v)),float(max(v))) for k,v in rep.items()}; log(f"repeated CV {R['repcv']}")
    save(R)
    pd.set_option('display.width',250); print(aud.round(3).to_string(index=False))

