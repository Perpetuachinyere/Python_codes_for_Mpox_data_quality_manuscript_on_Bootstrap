def parse_age(v):
    if pd.isna(v): return np.nan
    v=str(v).strip()
    if '-' in v:
        try:
            n=[float(p) for p in v.split('-') if p.replace('.','').isdigit()]
            return np.mean(n) if n and max(n)<130 else np.nan
        except: return np.nan
    try: return float(v)
    except: return np.nan
df['Age_numeric'] = df['Age'].apply(parse_age)
z = (df['Age_numeric']-df['Age_numeric'].mean())/df['Age_numeric'].std()
N_OUT = int((z.abs()>3).sum()); df.loc[z.abs()>3,'Age_numeric']=np.nan   # unsupervised, label-free
