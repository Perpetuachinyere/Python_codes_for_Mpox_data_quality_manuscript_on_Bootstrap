R=load()
if 'audit' not in R:
    from sklearn.metrics import average_precision_score
    R=load(); raw=pd.read_excel(DATA)
    # (a) field-by-field audit of all 35 columns
    rows=[]
    for c in raw.columns:
        miss=raw[c].isna().astype(int).values
        a=roc_auc_score(y,1-miss) if 0<miss.sum()<len(miss) else 0.5
        rows.append(dict(field=c,miss_all=miss.mean(),miss_conf=miss[y==1].mean(),miss_nonconf=miss[y==0].mean(),
                         missing_indicator_auc=max(a,1-a),n_unique=int(raw[c].nunique())))
    aud=pd.DataFrame(rows); R['audit']=aud; log("audit done")
    # (b) bootstrap CIs for the full metric set (record-level, out-of-fold predictions, 0.5 threshold)
    def mets(yt,p):
        pr=(p>=.5).astype(int); tp=((pr==1)&(yt==1)).sum(); tn=((pr==0)&(yt==0)).sum(); fp=((pr==1)&(yt==0)).sum(); fn=((pr==0)&(yt==1)).sum()
        sens=tp/(tp+fn); spec=tn/(tn+fp) if tn+fp else np.nan
        den=np.sqrt(float(tp+fp)*(tp+fn)*(tn+fp)*(tn+fn)); mcc=(tp*tn-fp*fn)/den if den else 0
        f1p=2*tp/(2*tp+fp+fn); f1n=2*tn/(2*tn+fn+fp) if (2*tn+fn+fp) else 0
        return dict(sens=sens,spec=spec,bacc=(sens+spec)/2,mcc=mcc,f1_pos=f1p,f1_neg=f1n,prauc=average_precision_score(yt,p))
    ext={}; rng=np.random.RandomState(42)
    for s in 'AB':
        for nm in R[s]:
            p=R[s][nm]['probs']; pt=mets(y,p); bs={k:[] for k in pt}
            for _ in range(300):
                i=rng.choice(len(y),len(y),replace=True); m=mets(y[i],p[i])
                for k,v in m.items(): bs[k].append(v)
            ext[(s,nm)]={k:(pt[k],np.nanpercentile(bs[k],2.5),np.nanpercentile(bs[k],97.5)) for k in pt}
        log(f"ext metrics {s}")
    R['ext']=ext
    # (c) country-cluster bootstrap (resample countries) on out-of-fold GBM predictions
    cty=df['Country'].values; codes,uni=pd.factorize(cty); idx_by=[np.where(codes==g)[0] for g in range(len(uni))]
    pA=R['A']['Gradient Boosting']['probs']; pB=R['B']['Gradient Boosting']['probs']; cb={'A':[],'B':[],'d':[]}
