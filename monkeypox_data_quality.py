KW={'rash':r'rash|lesion|pustul|vesicul|blister|spot|eruption','fever':r'fever|febrile|temperature',
 'lymphadenopathy':r'lymph|adenopath','genital':r'genital|anal|perianal','ulcer':r'ulcer',
 'headache':r'headache|cephalea','fatigue':r'fatigue|weakness|malaise','respiratory':r'cough|breath|dyspnea'}
s = df['Symptoms'].fillna('').str.lower()
