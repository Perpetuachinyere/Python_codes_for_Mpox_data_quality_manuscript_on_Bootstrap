def make_pre(country=True, mice=False, extra_month=False):
    tr=[]
    if country: tr.append(('cty',TargetEncoder(target_type='binary',random_state=42),['Country']))
    numcols=['Age_numeric','Age_bin']
    if mice: tr.append(('imp',Pipeline([('i',IterativeImputer(max_iter=5,random_state=42,sample_posterior=False)),('s',StandardScaler())]),numcols+['Gender_bin']))
    else:
        tr.append(('num',Pipeline([('i',SimpleImputer(strategy='median',keep_empty_features=True)),('s',StandardScaler())]),numcols))
        tr.append(('gen',Pipeline([('i',SimpleImputer(strategy='most_frequent',keep_empty_features=True)),('s',StandardScaler())]),['Gender_bin']))
    rest=FLAGS+SYM+(['month','date_missing'] if extra_month else [])
    if extra_month: tr.append(('mon',Pipeline([('i',SimpleImputer(strategy='median',keep_empty_features=True)),('s',StandardScaler())]),['month']))
    tr.append(('rest',StandardScaler(),[c for c in rest if c!='month']))
    return ColumnTransformer(tr)
def feats(country=True, extra_month=False):
    return (['Country'] if country else [])+['Age_numeric','Age_bin','Gender_bin']+FLAGS+SYM+(['month','date_missing'] if extra_month else [])

CLFS={'Logistic Regression':LogisticRegression(random_state=42),
 'Random Forest':RandomForestClassifier(random_state=42,n_jobs=-1),
 'Gradient Boosting':GradientBoostingClassifier(random_state=42),
 'XGBoost':XGBClassifier(random_state=42,eval_metric='logloss',verbosity=0)}
GRID={'Logistic Regression':{'clf__C':[0.01,0.1,1,10],'clf__max_iter':[1000]},
 'Random Forest':{'clf__n_estimators':[100],'clf__max_depth':[None,10],'clf__min_samples_split':[2,5]},
 'Gradient Boosting':{'clf__n_estimators':[100],'clf__learning_rate':[0.05,0.1],'clf__max_depth':[3,5]},
 'XGBoost':{'clf__n_estimators':[100],'clf__learning_rate':[0.05,0.1],'clf__max_depth':[3,5]}}
OUT=StratifiedKFold(5,shuffle=True,random_state=42); INN=StratifiedKFold(3,shuffle=True,random_state=42)
def ks(yt,p):
    a=p[yt==1]; b=p[yt==0]
    return stats.ks_2samp(a,b)[0] if len(a) and len(b) else np.nan
def boot(yt,p,fn,n=500,seed=42):
    r=np.random.RandomState(seed); v=[]
    for _ in range(n):
        i=r.choice(len(yt),len(yt),replace=True)
        try: v.append(fn(yt[i],p[i]))
        except: pass
    v=np.array(v); return np.percentile(v,2.5),np.percentile(v,97.5)
def ece(yt,p,b=10):
    e=np.linspace(0,1,b+1); t=0
    for lo,hi in zip(e[:-1],e[1:]):
        m=(p>=lo)&((p<hi)|(hi==1)&(p<=hi))
        if m.sum(): t+=m.sum()/len(yt)*abs(yt[m].mean()-p[m].mean())
    return t
def pipe(clf,**kw): return Pipeline([('pre',make_pre(**kw)),('clf',clf)])

def scenario(name,country):
    res={}; X=df[feats(country)]
    for nm,c in CLFS.items():
        gs=GridSearchCV(pipe(c,country=country),GRID[nm],cv=INN,scoring='roc_auc',n_jobs=-1)
        p=cross_val_predict(gs,X,y,cv=OUT,method='predict_proba',n_jobs=-1)[:,1]
        pr=(p>=.5).astype(int); tn,fp,fn,tp=confusion_matrix(y,pr).ravel()
        alo,ahi=boot(y,p,roc_auc_score); klo,khi=boot(y,p,ks)
        pl=np.zeros_like(p); iso=np.zeros_like(p)
        for tr,te in OUT.split(X,y):
            l=LogisticRegression(max_iter=500).fit(p[tr].reshape(-1,1),y[tr]); pl[te]=l.predict_proba(p[te].reshape(-1,1))[:,1]
            iso[te]=IsotonicRegression(out_of_bounds='clip').fit(p[tr],y[tr]).predict(p[te])
        res[nm]=dict(probs=p,auc=roc_auc_score(y,p),auc_lo=alo,auc_hi=ahi,ks=ks(y,p),ks_lo=klo,ks_hi=khi,
          sens=tp/(tp+fn),spec=tn/(tn+fp),bacc=balanced_accuracy_score(y,pr),mcc=matthews_corrcoef(y,pr),
          prauc=average_precision_score(y,p),f1=f1_score(y,pr),brier=brier_score_loss(y,p),ece=ece(y,p),
          tp=int(tp),tn=int(tn),fp=int(fp),fn=int(fn),
          cal={k:dict(auc=roc_auc_score(y,q),ks=ks(y,q),brier=brier_score_loss(y,q),ece=ece(y,q)) for k,q in
               [('raw',p),('platt',pl),('isotonic',iso)]})
        log(f"{name} {nm}: AUC={res[nm]['auc']:.4f} KS={res[nm]['ks']:.4f} sens={res[nm]['sens']:.3f} spec={res[nm]['spec']:.3f}")
    return res


